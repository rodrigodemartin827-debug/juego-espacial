def _valores():
    """Numera los minerales y reparte el valor dentro del rango de cada rareza (de menos a más)."""
    for i, d in enumerate(MINERALES):
        d["n"] = i + 1
        d.setdefault("semilla", 1000 + i * 37)
    por_rareza = {}
    for d in MINERALES:
        por_rareza.setdefault(d["rareza"], []).append(d)
    for rar, lista in por_rareza.items():
        lo, hi = RAREZAS[rar]["valor"]
        assert len(lista) == RAREZAS[rar]["cantidad"], (rar, len(lista))
        for k, d in enumerate(lista):
            d.setdefault("valor", round(lo + (hi - lo) * k / max(1, len(lista) - 1)))
    # roca_gravitacional: la roca es más pequeña que el conjunto (deja sitio a las órbitas)
    for d in MINERALES:
        if d.get("tam_roca"):
            d["tam_orbitas"] = d["tam"]
    assert len(MINERALES) == 100


_valores()
