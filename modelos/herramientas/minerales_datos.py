def Pt(patron="manchas", c=("#8A8780", "#5E5B56"), rug=0.85, met=0.0, capas=(), **kw):
    d = dict(patron=patron, c=list(c), rug=rug, met=met, capas=list(capas))
    d.update(kw)
    return d


def V(c, a=0.5, **kw):  # vetas
    return dict(t="vetas", c=c, a=a, **kw)


def G(c, a=0.6, **kw):  # pintar las grietas/poros del relieve
    return dict(t="grietas", c=c, a=a, **kw)


def M(c, a=0.25, **kw):  # motas
    return dict(t="motas", c=c, a=a, **kw)


def A(c, a=0.45, **kw):  # lo que mira arriba (musgo, escarcha, polvo)
    return dict(t="arriba", c=c, a=a, **kw)


def MA(c, a=0.3, **kw):  # manchas
    return dict(t="manchas", c=c, a=a, **kw)


def CR(color, rug=0.06, emi=None, ef=0.4, patron="liso", c2=None, **kw):
    """Pintura de cristal."""
    cols = kw.pop("c", None) or (color, c2 or color)
    return Pt(patron, cols, rug=rug, emi=emi, ef=ef if emi else 0.0, oscurecer_base=0.1, **kw)


def NE(color, ef=1.0, c2=None, patron="liso", **kw):
    """Pintura de Neon (lo que brilla)."""
    cols = kw.pop("c", None) or (color, c2 or color)
    return Pt(patron, cols, rug=0.3, emi=color, ef=ef, oscurecer_base=0.0, **kw)


